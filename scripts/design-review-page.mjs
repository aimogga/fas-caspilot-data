// design-review-page: builds docs/design/reviews/index.html (generated, see harness/generated-files.json) from every
// docs/design/reviews/*/manifest.json that scripts/design-shots.mjs wrote. Usage: pnpm review-page
// One section per route for its newest packet id: before and after side by side per width, then hover/focus/print/dark.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT, fileName, slug } from './design-shots.mjs';

const VARIANTS = ['base', 'hover', 'focus', 'print', 'dark'];
const TAGS = ['before', 'after'];
const rank = (v) => (VARIANTS.includes(v) ? VARIANTS.indexOf(v) : VARIANTS.length);
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const CSS = [
  ':root { --bg: oklch(0.975 0.008 85); --fg: oklch(0.22 0.012 70); --muted: oklch(0.48 0.015 70); --line: oklch(0.89 0.012 80); --green: oklch(0.38 0.06 160); }',
  'body { margin: 0; padding: 24px 16px 48px; background: var(--bg); color: var(--fg); font: 15px/1.5 Inter, ui-sans-serif, system-ui, sans-serif; }',
  'main { max-width: 1600px; margin: 0 auto; } h1 { font-size: 22px; margin: 0 0 4px; } p { margin: 0 0 8px; color: var(--muted); }',
  'h2 { font-size: 18px; margin: 40px 0 8px; padding-bottom: 6px; border-bottom: 2px solid var(--green); }',
  'h3 { font-size: 13px; font-weight: 600; letter-spacing: 0.04em; text-transform: uppercase; color: var(--muted); margin: 20px 0 8px; }',
  'code { font: 12px/1 ui-monospace, monospace; } .pair { display: flex; flex-wrap: wrap; gap: 16px; align-items: flex-start; }',
  'figure { flex: 1 1 320px; max-width: 760px; margin: 0; } img { display: block; width: 100%; height: auto; border: 1px solid var(--line); background: #fff; }',
  'figcaption { margin-top: 6px; font-size: 13px; color: var(--muted); } figcaption b { color: var(--green); }',
].join('\n');

function figure(e) {
  const src = `${e.id}/${e.tag}/${fileName(e.route, e.width, e.variant)}`;
  const caption = `${e.id} · ${e.tag} · ${e.width}`;
  const img = `<img src="${esc(src)}" alt="${esc(`${e.route} ${e.variant} ${caption}`)}" loading="lazy">`;
  return `<figure>${img}<figcaption><b>${esc(e.tag)}</b> ${esc(caption)} · <code>${esc(e.sha)}</code></figcaption></figure>`;
}

/** The packet whose latest shot is newest wins the route; the last row saved for a width, variant and tag is the one shown. */
function section(route, entries) {
  const newest = entries.reduce((a, b) => (String(b.at) > String(a.at) ? b : a)).id;
  const shots = entries.filter((e) => e.id === newest);
  const keys = [...new Set(shots.map((e) => `${e.width}|${e.variant}`))].map((k) => k.split('|'))
    .sort((a, b) => rank(a[1]) - rank(b[1]) || Number(a[0]) - Number(b[0]));
  const groups = keys.map(([width, variant]) => {
    const pair = TAGS.map((tag) => shots.filter((e) => String(e.width) === width && e.variant === variant && e.tag === tag).pop()).filter(Boolean);
    return `<h3>${esc(width)} · ${esc(variant)}</h3>\n<div class="pair">${pair.map(figure).join('')}</div>`;
  });
  return `<section id="route-${esc(slug(route))}">\n<h2>${esc(route)} · ${esc(newest)}</h2>\n${groups.join('\n')}\n</section>`;
}

/** Pure: manifests (one array per packet, or one flat list of rows) to the whole page; image paths stay relative to index.html. */
export function buildHtml(manifests) {
  const entries = manifests.flat().filter((e) => e && e.route);
  const routes = [...new Set(entries.map((e) => e.route))].sort();
  const body = routes.length
    ? routes.map((route) => section(route, entries.filter((e) => e.route === route))).join('\n')
    : '<p>No shots yet. Run <code>pnpm shots</code> for a packet, then <code>pnpm review-page</code>.</p>';
  return [
    '<!doctype html>', '<html lang="en">', '<head>', '<meta charset="utf-8">', '<meta name="viewport" content="width=device-width, initial-scale=1">',
    '<title>Design review shots</title>', `<style>\n${CSS}\n</style>`, '</head>', '<body>', '<main>', '<h1>Design review shots</h1>',
    '<p>Generated by <code>pnpm review-page</code> from <code>docs/design/reviews/*/manifest.json</code>: the newest packet per route, before on the left and after on the right.</p>',
    body, '</main>', '</body>', '</html>', '',
  ].join('\n');
}

export function main(root = ROOT) {
  mkdirSync(root, { recursive: true });
  const dirs = readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
  const files = dirs.map((id) => path.join(root, id, 'manifest.json')).filter((f) => existsSync(f));
  const out = path.join(root, 'index.html');
  writeFileSync(out, buildHtml(files.map((f) => JSON.parse(readFileSync(f, 'utf-8')))));
  return { out, packets: files.length };
}

